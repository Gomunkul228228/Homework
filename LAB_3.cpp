#include <iostream>
using namespace std;

// ==================== Задание 1 ====================
// Рекурсивный вывод чисел от 1 до n.
// Параметр i — вспомогательный. Значение по умолчанию (= 1)
// позволяет вызывать функцию как print1ToN(n), не передавая i вручную.
void print1ToN(int n, int i = 1) {
    if (i > n) return; // базовый случай рекурсии: вышли за верхнюю границу
    cout << i << " ";
    print1ToN(n, i + 1); // рекурсивный шаг: переходим к следующему числу
}

// ==================== Задание 2 ====================
// Рекурсивный вывод чисел от A до B включительно.
// Если A < B — идём вверх, если A > B — вниз.
void printAB(int a, int b) {
    cout << a << " ";
    if (a == b) return; // достигли конечного числа — останавливаемся

    if (a < b)
        printAB(a + 1, b); // движение вверх
    else
        printAB(a - 1, b); // движение вниз
}

// ==================== Задание 3 ====================
// Рекурсивная сумма цифр числа n.
// Предполагается, что n >= 0.
int sumDigits(int n) {
    if (n == 0) return 0; // базовый случай: цифр больше нет

    // n % 10 — последняя цифра числа
    // n / 10 — число без последней цифры (целочисленное деление)
    return n % 10 + sumDigits(n / 10);
}

int main() {
    // ---------- Задание 1 ----------
    cout << "Задание 1" << endl;
    int n;
    cin >> n;
    print1ToN(n);
    cout << endl;

    // ---------- Задание 2 ----------
    cout << "Задание 2" << endl;
    int A, B;
    cin >> A >> B;
    printAB(A, B);
    cout << endl;

    // ---------- Задание 3 ----------
    cout << "Задание 3" << endl;
    int N;
    cin >> N;
    cout << sumDigits(N) << endl;

    return 0;
}